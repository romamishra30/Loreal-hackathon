let initialLanguage = 'en'
if (typeof window !== 'undefined' && window.localStorage) {
  try {
    const raw = window.localStorage.getItem('refillrx-store')
    if (raw) {
      const parsed = JSON.parse(raw)
      if (parsed?.state?.language && ['en', 'hi', 'mr'].includes(parsed.state.language)) {
        initialLanguage = parsed.state.language
      }
    }
  } catch {
    // fallback
  }
}

i18n
  .use(initReactI18next)
  .init({
    resources: {
      en: { translation: defaultEnTranslations },
      hi: { translation: defaultHiTranslations },
      mr: { translation: defaultMrTranslations },
    },
    lng: initialLanguage,
    fallbackLng: 'en',
    interpolation: {
      escapeValue: false,
    },
    missingKeyHandler: (lngs, ns, key) => {
      if (process.env.NODE_ENV !== 'production') {
        console.warn(`[i18n] Missing translation key "${key}" in language "${lngs}"`)
      }
    }
  })

export const t = (key: string, options?: any): string => i18n.t(key, options) as string
export const setLanguage = (lang: 'en' | 'hi' | 'mr') => {
  i18n.changeLanguage(lang)
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang
  }
}
export const getLanguage = () => i18n.language

export default i18n
